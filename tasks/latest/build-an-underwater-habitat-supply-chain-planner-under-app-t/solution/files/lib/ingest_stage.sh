#!/usr/bin/env bash
set -euo pipefail
APP_ROOT="${APP_ROOT:-/app}"
source "${APP_ROOT}/lib/common.sh"
root="/app/data/mission"
[[ $# -ge 1 && -n "${1:-}" ]] && root="$1"
[[ -n "${RESUPPLY_MISSION_DIR:-}" ]] && root="${RESUPPLY_MISSION_DIR}"
[[ "$root" = /* ]] || { echo "mission dir must be absolute" >&2; exit 1; }
ensure_dirs
parsed="$(bash "${APP_ROOT}/lib/parse_mission.sh" "$root")"
mh="$(bash "${APP_ROOT}/lib/mission_hash.sh" "$parsed")"
hab="$(python3 -c 'import json,sys; print(json.dumps(json.loads(sys.argv[1])["habitat"]))' "$parsed")"
tide="$(bash "${APP_ROOT}/lib/tide_snapshot.sh" "$parsed" "$mh")"
tide="$(bash "${APP_ROOT}/lib/lane_window.sh" "$tide" "$hab")"
tide="$(bash "${APP_ROOT}/lib/wave_buffer.sh" "$tide" "$hab")"
echo "$tide" > "${TIDE_SNAPSHOT}"
rov="$(bash "${APP_ROOT}/lib/rov_slot.sh" "$tide" "$hab")"
echo "$rov" > "${ROV_INDEX}"
ledger="$(bash "${APP_ROOT}/lib/priority_ledger.sh" "$tide" "$hab")"
freeze="$(bash "${APP_ROOT}/lib/o2_freeze.sh" "$ledger" "$(python3 -c 'import json,sys; print(json.loads(sys.argv[1])["tide_hash"])' "$tide")")"
echo "$freeze" > "${O2_FREEZE}"
staged="$(bash "${APP_ROOT}/lib/berth_assign.sh" "$ledger" "$hab")"
budgeted="$(bash "${APP_ROOT}/lib/cold_budget.sh" "$staged" "$hab")"
echo "$budgeted" > "${BERTH_STAGING}"
cert="$(bash "${APP_ROOT}/lib/transfer_cert.sh" "$budgeted" "$hab")"
echo "$cert" > "${TRANSFER_CERT}"
bound="$(bash "${APP_ROOT}/lib/staging_bind.sh" "$budgeted" "$mh" "$hab" "$rov" "$cert")"
echo "$bound" > "${EXPORT_BIND}"
seq="$(bash "${APP_ROOT}/lib/run_sequence.sh")"
bash "${APP_ROOT}/lib/ingest_manifest.sh" "$mh" "$bound" "$seq" "${INGEST_MANIFEST}"
