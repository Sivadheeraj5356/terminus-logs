// hmm - exact replay and likelihood analysis of the duration-explicit
// recording process, from scratch, Go standard library only.
//
// For each case (model parameters plus a 64-bit SEED) it
//   - regenerates the exact recording the reference process emits for that
//     seed, drawing uniforms from the documented splitmix64 stream with the
//     reference's consumption conventions: at window open one draw for the
//     opening state (categorical scan, first index with u < cumulative sum),
//     one draw for the elapsed dwell of the visit in progress (residual-life
//     law S_i(u)/mean_i), one draw for that visit's total duration
//     (conditional law D_i(d)/S_i(u) on d >= u); no draws while a visit runs;
//     at each visit end one draw for the next state (A row) then one draw for
//     its total duration (D row); at each step the symbol draw is taken first
//     and always (B row of the generating state, which lags one step behind),
//     then the missingness draw ('?' iff it is < m_s); a masked entry still
//     consumed its symbol draw;
//   - computes the log-likelihood of that recording and the posterior
//     expected number of visits the window intersects, exactly under the same
//     semantics (residual-life window opening, one-step lag, state-dependent
//     missingness, right censoring at T), on the dwell-augmented chain in log
//     space so the computation stays finite for arbitrarily long recordings.
package main

import (
	"bufio"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const missing = -1

var negInf = math.Inf(-1)

func lse2(a, b float64) float64 {
	if math.IsInf(a, -1) {
		return b
	}
	if math.IsInf(b, -1) {
		return a
	}
	if a < b {
		a, b = b, a
	}
	return a + math.Log1p(math.Exp(b-a))
}

func safeLog(x float64) float64 {
	if x <= 0 {
		return negInf
	}
	return math.Log(x)
}

type caseData struct {
	id      string
	n, k, t int
	dmax    int
	seed    uint64
	pi      []float64
	a       [][]float64
	b       [][]float64
	d       [][]float64
	m       []float64
}

type model struct {
	n, dmax      int
	logA         [][]float64
	logB         [][]float64
	mm           []float64
	logH, log1mH [][]float64 // indexed [i][u], u in 1..dmax
	logStart     [][]float64 // indexed [i][u-1]
}

func newModel(c *caseData) *model {
	m := &model{n: c.n, dmax: c.dmax, mm: c.m}
	m.logA = make([][]float64, c.n)
	m.logB = make([][]float64, c.n)
	m.logH = make([][]float64, c.n)
	m.log1mH = make([][]float64, c.n)
	m.logStart = make([][]float64, c.n)
	for i := 0; i < c.n; i++ {
		m.logA[i] = make([]float64, c.n)
		for j := 0; j < c.n; j++ {
			m.logA[i][j] = safeLog(c.a[i][j])
		}
		m.logB[i] = make([]float64, c.k)
		for k := 0; k < c.k; k++ {
			m.logB[i][k] = safeLog(c.b[i][k])
		}
		m.logH[i] = make([]float64, c.dmax+1)
		m.log1mH[i] = make([]float64, c.dmax+1)
		m.logStart[i] = make([]float64, c.dmax)
		surv := make([]float64, c.dmax+2)
		acc := 0.0
		for d := c.dmax; d >= 1; d-- {
			acc += c.d[i][d-1]
			surv[d] = acc
		}
		mean := 0.0
		for d := 1; d <= c.dmax; d++ {
			mean += float64(d) * c.d[i][d-1]
		}
		for u := 1; u <= c.dmax; u++ {
			m.logStart[i][u-1] = negInf
			if surv[u] <= 0 {
				m.logH[i][u] = negInf
				m.log1mH[i][u] = negInf
				continue
			}
			m.logH[i][u] = safeLog(c.d[i][u-1] / surv[u])
			m.log1mH[i][u] = safeLog(surv[u+1] / surv[u])
			lp := safeLog(c.pi[i])
			if !math.IsInf(lp, -1) {
				m.logStart[i][u-1] = lp + safeLog(surv[u]/mean)
			}
		}
	}
	return m
}

// rec is the log factor of the entry recorded at step t, generated by state s.
func (m *model) rec(obs []int, t, s int) float64 {
	if obs[t] == missing {
		return safeLog(m.mm[s])
	}
	return safeLog(1.0-m.mm[s]) + m.logB[s][obs[t]]
}

func (m *model) solve(obs []int) (float64, [][]float64, float64) {
	n, dmax := m.n, m.dmax
	t := len(obs)
	la := make([][][]float64, t)
	lb := make([][][]float64, t)
	for s := 0; s < t; s++ {
		la[s] = make([][]float64, n)
		lb[s] = make([][]float64, n)
		for i := 0; i < n; i++ {
			la[s][i] = make([]float64, dmax)
			lb[s][i] = make([]float64, dmax)
			for u := 0; u < dmax; u++ {
				la[s][i][u] = negInf
				lb[s][i][u] = negInf
			}
		}
	}
	for i := 0; i < n; i++ {
		e0 := m.rec(obs, 0, i)
		for u := 0; u < dmax; u++ {
			if !math.IsInf(m.logStart[i][u], -1) {
				la[0][i][u] = m.logStart[i][u] + e0
			}
		}
	}
	for s := 1; s < t; s++ {
		prev, cur := la[s-1], la[s]
		exit := make([]float64, n)
		for i := 0; i < n; i++ {
			acc := negInf
			for u := 1; u <= dmax; u++ {
				v := prev[i][u-1]
				if !math.IsInf(v, -1) && !math.IsInf(m.logH[i][u], -1) {
					acc = lse2(acc, v+m.logH[i][u])
				}
			}
			if !math.IsInf(acc, -1) {
				acc += m.rec(obs, s, i) // lag: entry s from source state i
			}
			exit[i] = acc
		}
		for j := 0; j < n; j++ {
			acc := negInf
			for i := 0; i < n; i++ {
				if !math.IsInf(exit[i], -1) && !math.IsInf(m.logA[i][j], -1) {
					acc = lse2(acc, exit[i]+m.logA[i][j])
				}
			}
			cur[j][0] = acc
			eStay := m.rec(obs, s, j)
			for u := 1; u < dmax; u++ {
				v := prev[j][u-1]
				if !math.IsInf(v, -1) && !math.IsInf(m.log1mH[j][u], -1) {
					cur[j][u] = v + m.log1mH[j][u] + eStay
				}
			}
		}
	}
	loglik := negInf
	for i := 0; i < n; i++ {
		for u := 0; u < dmax; u++ {
			loglik = lse2(loglik, la[t-1][i][u])
		}
	}

	for i := 0; i < n; i++ {
		for u := 0; u < dmax; u++ {
			lb[t-1][i][u] = 0
		}
	}
	for s := t - 2; s >= 0; s-- {
		nxt, cur := lb[s+1], lb[s]
		jumpc := make([]float64, n)
		for i := 0; i < n; i++ {
			acc := negInf
			for j := 0; j < n; j++ {
				if !math.IsInf(nxt[j][0], -1) && !math.IsInf(m.logA[i][j], -1) {
					acc = lse2(acc, m.logA[i][j]+nxt[j][0])
				}
			}
			jumpc[i] = acc
		}
		for i := 0; i < n; i++ {
			eI := m.rec(obs, s+1, i) // lag: entry s+1 from source state i
			for u := 1; u <= dmax; u++ {
				stay := negInf
				if u < dmax && !math.IsInf(m.log1mH[i][u], -1) &&
					!math.IsInf(nxt[i][u], -1) {
					stay = m.log1mH[i][u] + nxt[i][u]
				}
				jump := negInf
				if !math.IsInf(m.logH[i][u], -1) && !math.IsInf(jumpc[i], -1) {
					jump = m.logH[i][u] + jumpc[i]
				}
				v := lse2(stay, jump)
				if !math.IsInf(v, -1) {
					v += eI
				}
				cur[i][u-1] = v
			}
		}
	}

	gamma := make([][]float64, t)
	for s := 0; s < t; s++ {
		gamma[s] = make([]float64, n)
		for i := 0; i < n; i++ {
			acc := negInf
			for u := 0; u < dmax; u++ {
				va, vb := la[s][i][u], lb[s][i][u]
				if !math.IsInf(va, -1) && !math.IsInf(vb, -1) {
					acc = lse2(acc, va+vb)
				}
			}
			if math.IsInf(acc, -1) {
				gamma[s][i] = 0
			} else {
				gamma[s][i] = math.Exp(acc - loglik)
			}
		}
	}

	nseg := 1.0
	for s := 0; s < t-1; s++ {
		acc := negInf
		for i := 0; i < n; i++ {
			ex := negInf
			for u := 1; u <= dmax; u++ {
				v := la[s][i][u-1]
				if !math.IsInf(v, -1) && !math.IsInf(m.logH[i][u], -1) {
					ex = lse2(ex, v+m.logH[i][u])
				}
			}
			if math.IsInf(ex, -1) {
				continue
			}
			ex += m.rec(obs, s+1, i)
			for j := 0; j < n; j++ {
				if !math.IsInf(lb[s+1][j][0], -1) && !math.IsInf(m.logA[i][j], -1) {
					acc = lse2(acc, ex+m.logA[i][j]+lb[s+1][j][0])
				}
			}
		}
		if !math.IsInf(acc, -1) {
			nseg += math.Exp(acc - loglik)
		}
	}
	return loglik, gamma, nseg
}


type stream struct{ z uint64 }

func (r *stream) next() uint64 {
	r.z += 0x9E3779B97F4A7C15
	x := r.z
	x = (x ^ (x >> 30)) * 0xBF58476D1CE4E5B9
	x = (x ^ (x >> 27)) * 0x94D049BB133111EB
	return x ^ (x >> 31)
}

func (r *stream) uniform() float64 {
	return float64(r.next()>>11) / (1 << 53)
}

func pick(u float64, w []float64) int {
	acc := 0.0
	for i, v := range w {
		acc += v
		if u < acc {
			return i
		}
	}
	return len(w) - 1
}

// sample regenerates the exact recording for the case's seed under the
// reference consumption conventions.
func sample(c *caseData) []int {
	rng := &stream{z: c.seed}
	surv := make([][]float64, c.n)
	mean := make([]float64, c.n)
	for i := 0; i < c.n; i++ {
		surv[i] = make([]float64, c.dmax+2)
		acc := 0.0
		for d := c.dmax; d >= 1; d-- {
			acc += c.d[i][d-1]
			surv[i][d] = acc
		}
		for d := 1; d <= c.dmax; d++ {
			mean[i] += float64(d) * c.d[i][d-1]
		}
	}
	state := pick(rng.uniform(), c.pi)
	offw := make([]float64, c.dmax)
	for u := 1; u <= c.dmax; u++ {
		offw[u-1] = surv[state][u] / mean[state]
	}
	elapsed := pick(rng.uniform(), offw) + 1
	condw := make([]float64, c.dmax)
	for d := elapsed; d <= c.dmax; d++ {
		condw[d-1] = c.d[state][d-1] / surv[state][elapsed]
	}
	total := pick(rng.uniform(), condw) + 1
	remaining := total - elapsed + 1

	states := make([]int, c.t)
	for t := 0; t < c.t; t++ {
		states[t] = state
		remaining--
		if remaining == 0 {
			state = pick(rng.uniform(), c.a[state])
			remaining = pick(rng.uniform(), c.d[state]) + 1
		}
	}
	obs := make([]int, c.t)
	for t := 0; t < c.t; t++ {
		s := states[t]
		if t >= 1 {
			s = states[t-1]
		}
		k := pick(rng.uniform(), c.b[s])
		if rng.uniform() < c.m[s] {
			obs[t] = missing
		} else {
			obs[t] = k
		}
	}
	return obs
}

func parseCases(path string) ([]*caseData, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	lines := strings.Split(string(raw), "\n")
	var cases []*caseData
	i := 0
	skip := func() {
		for i < len(lines) {
			s := strings.TrimSpace(lines[i])
			if s == "" || strings.HasPrefix(s, "#") {
				i++
				continue
			}
			return
		}
	}
	for {
		skip()
		if i >= len(lines) {
			break
		}
		line := strings.TrimSpace(lines[i])
		if !strings.HasPrefix(line, "CASE") {
			return nil, fmt.Errorf("expected CASE, got %q", line)
		}
		c := &caseData{id: strings.TrimSpace(strings.TrimPrefix(line, "CASE"))}
		i++
		skip()
		var tagN, tagK, tagT, tagD string
		if _, err := fmt.Sscan(lines[i], &tagN, &c.n, &tagK, &c.k, &tagT,
			&c.t, &tagD, &c.dmax); err != nil {
			return nil, fmt.Errorf("bad dims line %q: %v", lines[i], err)
		}
		i++
		skip()
		var tagS string
		if _, err := fmt.Sscan(lines[i], &tagS, &c.seed); err != nil ||
			tagS != "SEED" {
			return nil, fmt.Errorf("bad SEED line %q", lines[i])
		}
		i++
		readRow := func(prefix string, want int) ([]float64, error) {
			skip()
			toks := strings.Fields(lines[i])
			if len(toks) != want+1 || toks[0] != prefix {
				return nil, fmt.Errorf("expected %s row with %d values, got %q",
					prefix, want, lines[i])
			}
			row := make([]float64, want)
			for j, tk := range toks[1:] {
				v, err := strconv.ParseFloat(tk, 64)
				if err != nil {
					return nil, err
				}
				row[j] = v
			}
			i++
			return row, nil
		}
		var err error
		if c.pi, err = readRow("PI", c.n); err != nil {
			return nil, err
		}
		for r := 0; r < c.n; r++ {
			row, err := readRow("A", c.n)
			if err != nil {
				return nil, err
			}
			c.a = append(c.a, row)
		}
		for r := 0; r < c.n; r++ {
			row, err := readRow("B", c.k)
			if err != nil {
				return nil, err
			}
			c.b = append(c.b, row)
		}
		for r := 0; r < c.n; r++ {
			row, err := readRow("D", c.dmax)
			if err != nil {
				return nil, err
			}
			c.d = append(c.d, row)
		}
		if c.m, err = readRow("M", c.n); err != nil {
			return nil, err
		}
		skip()
		if strings.TrimSpace(lines[i]) != "END" {
			return nil, fmt.Errorf("expected END for %s, got %q", c.id, lines[i])
		}
		i++
		cases = append(cases, c)
	}
	return cases, nil
}

func main() {
	inPath := "/app/data/cases.txt"
	outPath := "/app/output/results.txt"
	if len(os.Args) > 1 {
		inPath = os.Args[1]
	}
	if len(os.Args) > 2 {
		outPath = os.Args[2]
	}
	cases, err := parseCases(inPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "parse error:", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	f, err := os.Create(outPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	w := bufio.NewWriter(f)
	for _, c := range cases {
		obs := sample(c)
		m := newModel(c)
		loglik, _, nseg := m.solve(obs)
		fmt.Fprintf(w, "CASE %s\n", c.id)
		w.WriteString("O")
		for _, o := range obs {
			if o == missing {
				w.WriteString(" ?")
			} else {
				fmt.Fprintf(w, " %d", o)
			}
		}
		w.WriteString("\n")
		fmt.Fprintf(w, "LOGLIK %.17g\n", loglik)
		fmt.Fprintf(w, "NSEG %.17g\n", nseg)
		w.WriteString("END\n")
	}
	if err := w.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := f.Close(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
